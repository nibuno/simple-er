test("inline foreign key actions preserve all explicit options and leave omitted actions unset", () => {
  for (const action of [
    "CASCADE",
    "RESTRICT",
    "SET NULL",
    "SET DEFAULT",
    "NO ACTION",
  ]) {
    const sql = `CREATE TABLE p (id int PRIMARY KEY); CREATE TABLE c (id int REFERENCES p ON UPDATE ${action});`;
    const { diagram, issues } = importDDL(sql);
    assert.deepEqual(issues, []);
    const ddl = diagramDDL(diagram);
    assert.ok(ddl.includes("ON UPDATE " + action));
    assert.ok(!ddl.includes("ON DELETE"));
    const [fk] = importDDL(ddl).diagram.tables[1].foreignKeys;
    assert.equal(fk.onUpdate, action);
    assert.equal(fk.onDelete, undefined);
  }
});

