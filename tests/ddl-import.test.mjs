test("column generation, multiline notes and composite reference actions survive SQL and JSON round trips", () => {
  const note = "改行・空白・引用符を含む説明。".repeat(14) + "\nO'Brien  ";
  const quoted = note.replaceAll("'", "''");
  const sql = `CREATE TABLE child (
    tenant int NOT NULL, parent_id bigint, copies int DEFAULT (1 + 2),
    FOREIGN KEY (tenant, parent_id) REFERENCES parent (tenant, id)
      ON UPDATE NO ACTION ON DELETE SET DEFAULT
  );
  CREATE TABLE parent (
    tenant int, id bigint GENERATED ALWAYS AS IDENTITY (START WITH 15 INCREMENT BY 3),
    PRIMARY KEY (tenant, id)
  ) COMMENT='${quoted}';
  COMMENT ON COLUMN child.copies IS '${quoted}';`;
  const { diagram, issues } = importDDL(sql);
  assert.deepEqual(issues, []);
  const [child, parent] = diagram.tables;
  assert.equal(child.columns[0].notNull, true);
  assert.equal(child.columns[2].defaultValue, "(1 + 2)");
  assert.equal(child.foreignKeys[0].onDelete, "SET DEFAULT");
  assert.equal(child.foreignKeys[0].onUpdate, "NO ACTION");
  assert.equal(parent.columns[1].identity, "always");
  assert.equal(
    parent.columns[1].identityOptions,
    "START WITH 15 INCREMENT BY 3",
  );
  assert.equal(parent.note, note);
  assert.equal(child.columns[2].note, note);
  assert.equal(parent.logicalName, "");
  assert.equal(child.columns[2].logicalName, "");
  const ddl = diagramDDL(decode(encode(diagram)));
  assert.match(
    ddl,
    /ALTER TABLE child ADD FOREIGN KEY.*ON DELETE SET DEFAULT ON UPDATE NO ACTION/,
  );
  assert.match(
    ddl,
    /GENERATED ALWAYS AS IDENTITY \(START WITH 15 INCREMENT BY 3\)/,
  );
  const second = importDDL(ddl);
  assert.deepEqual(second.issues, []);
  assert.equal(diagramDDL(second.diagram), ddl);
  assert.equal(second.diagram.tables[0].columns[2].note, note);
});

