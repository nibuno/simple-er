test("comments and defaults can contain escaped quotes, semicolons and SQL keywords", () => {
  const source =
    "CREATE TABLE `people` (name text DEFAULT 'O\\'Brien' COMMENT '姓; O\\'Brien');\r\n" +
    'COMMENT ON TABLE people IS $msg$Names, "quoted"; -- example$msg$;';
  const { diagram, issues } = importDDL(source);
  assert.deepEqual(issues, []);
  assert.equal(diagram.tables[0].columns[0].note, "姓; O'Brien");
  assert.equal(diagram.tables[0].columns[0].defaultValue, "'O''Brien'");
  const ddl = diagramDDL(diagram);
  assert.equal(diagramDDL(importDDL(ddl).diagram), ddl);
});

test("a duplicate CREATE does not change the original table via later statements in the dump", () => {
  const { diagram: base } = importDDL(
    "create table customer(id int primary key);",
  );
  const { diagram, issues, applied } = importDDL(
    "CREATE TABLE customer(id int);\nCOMMENT ON TABLE customer IS '別の図';\nCREATE INDEX ix ON customer(id);",
    base,
  );
  assert.deepEqual(
    issues.map((i) => i.line),
    [1, 2, 3],
  );
  assert.equal(applied, 0);
  assert.deepEqual(diagram, base);
});

test("column modifiers retain a primary key after IDENTITY and the default before ON UPDATE", () => {
  const { diagram, issues } = importDDL(`CREATE TABLE events(
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    updated timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
  );`);
  assert.deepEqual(issues, []);
  const [id, updated] = diagram.tables[0].columns;
  assert.equal(id.key, "PK");
  assert.equal(updated.defaultValue, "CURRENT_TIMESTAMP");
  assert.equal(updated.notNull, true);
});

test("every bundled diagram round-trips the DDL written by SimpleER", async () => {
  const directory = new URL("../examples/", import.meta.url);
  const files = (await readdir(directory)).filter((file) =>
    file.endsWith(".json"),
  );
  const samples = [["初期の図", decode(JSON.stringify(initialDocument))]];
  for (const file of files)
    samples.push([
      file,
      decode(await readFile(new URL(file, directory), "utf8")),
    ]);
  for (const [file, original] of samples) {
    for (const dialect of ddlDialects) {
      const ddl = diagramDDL(original, dialect);
      const { diagram, issues } = importDDL(ddl);
      const label = file + " / " + dialect;
      assert.deepEqual(issues, [], label);
      assert.equal(diagramDDL(diagram, dialect), ddl, label);
      // Compare to the original schema in one spelling, including notes and keys.
      assert.equal(diagramDDL(diagram), diagramDDL(original), label);
      assert.equal(diagram.edges.length, original.edges.length, label);
      assert.ok(
        diagram.tables.every((t) => !overlaps(t, diagram.tables)),
        label,
      );
      if (dialect === "SQLite") {
        const db = new DatabaseSync(":memory:");
        try {
          db.exec(ddl);
          assert.deepEqual(db.prepare("PRAGMA foreign_key_check").all(), []);
        } finally {
          db.close();
        }
      }
    }
  }
});

test("named composite keys, quoted names, defaults, comments, and cycles survive a file round trip", () => {
  const source = `CREATE TABLE sales."Order" (
    tenant integer NOT NULL,
    id numeric(10, 2) DEFAULT (COALESCE(1, 2)),
    "join" text DEFAULT 'a,b;''c',
    CONSTRAINT "pk Order" PRIMARY KEY (tenant, id),
    FOREIGN KEY ("join") REFERENCES sales.people(code)
  );
  COMMENT ON COLUMN sales."Order"."join" IS 'it''s a; comment, -- text';
  CREATE TABLE sales.people (
    code text CONSTRAINT "uq code" UNIQUE,
    tenant integer, latest numeric(10, 2),
    CONSTRAINT "latest order" FOREIGN KEY (tenant, latest) REFERENCES sales."Order"(tenant, id)
  );
  CREATE INDEX by_latest ON sales.people (latest);
  COMMENT ON TABLE sales.people IS '担当者';`;
  const { diagram, issues } = importDDL(source);
  assert.deepEqual(issues, []);
  assert.equal(diagram.edges.length, 3);
  const [order, people] = diagram.tables;
  assert.equal(order.columns[0].notNull, true);
  assert.equal(order.columns[1].type, "numeric(10, 2)");
  assert.equal(order.columns[1].defaultValue, "(COALESCE(1, 2))");
  assert.equal(order.columns[2].defaultValue, "'a,b;''c'");
  assert.equal(order.columns[2].note, "it's a; comment, -- text");
  assert.equal(people.note, "担当者");
  const ddl = diagramDDL(decode(encode(diagram)));
  assert.match(ddl, /ALTER TABLE sales\."Order" ADD FOREIGN KEY/);
  assert.equal(diagramDDL(importDDL(ddl).diagram), ddl);
});

test("MySQL table options, inline references, named foreign keys and ALTER TABLE", () => {
  const { diagram, issues } = importDDL(`# schema
    CREATE TABLE IF NOT EXISTS \`member\` (
      \`id\` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
      name VARCHAR(50) COMMENT '氏名'
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='会員';
    /* ; */ CREATE TABLE visits (
      id int PRIMARY KEY, member_id bigint REFERENCES member,
      backup bigint, another bigint,
      KEY idx_visit (member_id),
      CONSTRAINT backup_fk FOREIGN KEY (backup) REFERENCES member (id) ON DELETE SET NULL
    );
    ALTER TABLE visits ADD CONSTRAINT another_fk FOREIGN KEY (another) REFERENCES member(id);`);
  assert.deepEqual(issues, []);
  assert.equal(diagram.edges.length, 3);
  assert.equal(diagram.tables[0].note, "会員");
  assert.equal(diagram.tables[0].columns[0].type, "BIGINT UNSIGNED");
  assert.equal(diagram.tables[0].columns[1].note, "氏名");
  assert.deepEqual(
    diagram.tables[1].foreignKeys.map((k) => k.name),
    ["", "backup_fk", "another_fk"],
  );
});

